-- ============================================================
-- issue #163: 弓種・室内外による得点方式の違いに対応する
--
-- インドアはリカーブ/ベアボウとコンパウンドで得点方式が異なる（アウトドアは
-- 弓種によらず共通の9,10,Xのため変更しない）。インドアにはXという区分自体が
-- 存在しない（弓種を問わず最高得点帯は常に"10"）。
--   - リカーブ/ベアボウ: 旧Xリングという区分自体が存在せず、その半径は10点として扱う。
--   - コンパウンド: 旧10リングという区分自体が存在せず、旧Xリングの半径からが
--     10点になり（score_strは"X"ではなく"10"）、その外側（旧10リング相当）は
--     9点になる。
-- リング半径・色は標準（9,10,X）のシードと完全に同一で、score_str/score_int
-- のみが異なる（データ形式は変更しない、supabase/docs/target-faces.md参照）。
--
-- 既存のインドア10点的（60cm・40cm、単一スポット・3つ目とも）はリカーブ/ベアボウ
-- 共通で使うため、旧Xリングを削除するのみで名称は変更しない。
-- コンパウンド用は新規の的として追加する（コンパウンド専用のため名前は英語表記）。
--
-- ついでに、最外周の境界線が欠けている（line_color = null）シード不整合を
-- 合わせて修正する（インドア3つ目の6点・アウトドア80cm 6点的の5点）。
-- ============================================================

-- ------------------------------------------------------------
-- 既存インドア的から旧Xリングを削除する（リカーブ・ベアボウ共通）
-- ------------------------------------------------------------

delete from target_face_rings
where score_str = 'X'
  and spot_id in (
    select s.id from target_face_spots s
    where s.target_face_id in (
      'a1000000-0000-0000-0000-000000000004', -- 10点的（インドア・60cm）
      'a1000000-0000-0000-0000-000000000005', -- 6点的（インドア・60cm・3つ目トライアングル）
      'a1000000-0000-0000-0000-000000000006', -- 6点的（インドア・60cm・3つ目バーティカル）
      'a1000000-0000-0000-0000-000000000007', -- 10点的（インドア・40cm）
      'a1000000-0000-0000-0000-000000000008', -- 6点的（インドア・40cm・3つ目トライアングル）
      'a1000000-0000-0000-0000-000000000009'  -- 6点的（インドア・40cm・3つ目バーティカル）
    )
  );

-- インドアの3つ目（6点的）は最外周が青（6点）で、境界線なし（line_color = null）で
-- シードされていたが、他の的の最外周（白1点等）が黒い境界線を持つのと不整合なため
-- 黒に修正する。
update target_face_rings
set line_color = '#231F20'
where score_str = '6'
  and line_color is null
  and spot_id in (
    select s.id from target_face_spots s
    where s.target_face_id in (
      'a1000000-0000-0000-0000-000000000005', -- 6点的（インドア・60cm・3つ目トライアングル）
      'a1000000-0000-0000-0000-000000000006', -- 6点的（インドア・60cm・3つ目バーティカル）
      'a1000000-0000-0000-0000-000000000008', -- 6点的（インドア・40cm・3つ目トライアングル）
      'a1000000-0000-0000-0000-000000000009'  -- 6点的（インドア・40cm・3つ目バーティカル）
    )
  );

-- 同様に6点的（アウトドア・80cm）も最外周が青（5点）で境界線なしのため黒に修正する
-- （こちらはインドアではないが、同じ「最外周の境界線が欠けている」不整合）。
update target_face_rings
set line_color = '#231F20'
where score_str = '5'
  and line_color is null
  and spot_id in (
    select s.id from target_face_spots s
    where s.target_face_id = 'a1000000-0000-0000-0000-000000000003' -- 6点的（アウトドア・80cm）
  );

