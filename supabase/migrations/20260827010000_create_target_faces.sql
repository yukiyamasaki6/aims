begin;

set lock_timeout = '1s';
set statement_timeout = '5s';

-- ============================================================
-- Tables
-- ============================================================

create table if not exists target_faces (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists target_face_spots (
  id uuid primary key default gen_random_uuid(),
  target_face_id uuid not null references target_faces (id) on delete cascade,
  center_x numeric not null,
  center_y numeric not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists target_face_rings (
  id uuid primary key default gen_random_uuid(),
  spot_id uuid not null references target_face_spots (id) on delete cascade,
  radius numeric not null,
  color text not null,
  line_color text,
  z_index bigint not null,
  score_str text not null,
  score_int bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (spot_id, z_index)
);

-- ============================================================
-- Row Level Security
-- ============================================================

alter table target_faces enable row level security;

grant select, insert, update, delete on target_faces to anon, authenticated;

create policy "select_all_authenticated" on target_faces
  for select
  to authenticated
  using (true);

create policy "insert_own" on target_faces
  for insert
  to authenticated
  with check (owner_id = auth.uid());

create policy "update_own" on target_faces
  for update
  to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());

create policy "delete_own" on target_faces
  for delete
  to authenticated
  using (owner_id = auth.uid());

alter table target_face_spots enable row level security;

grant select, insert, update, delete on target_face_spots to anon, authenticated;

create policy "select_all_authenticated" on target_face_spots
  for select
  to authenticated
  using (true);

create policy "insert_if_owner" on target_face_spots
  for insert
  to authenticated
  with check (
    exists (
      select 1 from target_faces tf
      where tf.id = target_face_spots.target_face_id and tf.owner_id = auth.uid()
    )
  );

create policy "update_if_owner" on target_face_spots
  for update
  to authenticated
  using (
    exists (
      select 1 from target_faces tf
      where tf.id = target_face_spots.target_face_id and tf.owner_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from target_faces tf
      where tf.id = target_face_spots.target_face_id and tf.owner_id = auth.uid()
    )
  );

create policy "delete_if_owner" on target_face_spots
  for delete
  to authenticated
  using (
    exists (
      select 1 from target_faces tf
      where tf.id = target_face_spots.target_face_id and tf.owner_id = auth.uid()
    )
  );

alter table target_face_rings enable row level security;

grant select, insert, update, delete on target_face_rings to anon, authenticated;

create policy "select_all_authenticated" on target_face_rings
  for select
  to authenticated
  using (true);

create policy "insert_if_owner" on target_face_rings
  for insert
  to authenticated
  with check (
    exists (
      select 1 from target_face_spots s
      join target_faces tf on tf.id = s.target_face_id
      where s.id = target_face_rings.spot_id and tf.owner_id = auth.uid()
    )
  );

create policy "update_if_owner" on target_face_rings
  for update
  to authenticated
  using (
    exists (
      select 1 from target_face_spots s
      join target_faces tf on tf.id = s.target_face_id
      where s.id = target_face_rings.spot_id and tf.owner_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from target_face_spots s
      join target_faces tf on tf.id = s.target_face_id
      where s.id = target_face_rings.spot_id and tf.owner_id = auth.uid()
    )
  );

create policy "delete_if_owner" on target_face_rings
  for delete
  to authenticated
  using (
    exists (
      select 1 from target_face_spots s
      join target_faces tf on tf.id = s.target_face_id
      where s.id = target_face_rings.spot_id and tf.owner_id = auth.uid()
    )
  );

