// 画面の遷移。go: 履歴を積んで進む。replace: 置き換える。
// 例外: 投げることがある(画面のパッケージが経路を受け付けないとき)。使う手続きはどれも扱わず、呼び出し元へ伝える。
// 保存の後に進む手続き(開始、完了、削除して離れる)は、保存が済んでいて、失敗として戻すと再び実行でき、成功として返すと遷移の失敗を隠すため、拒否として伝える。
// 保存を伴わない一覧へ戻る(leaveRound)は、例外をそのまま投げる(遷移の失敗を隠さない)。
export type Navigation = {
  go(path: string): void;
  replace(path: string): void;
};
