// 取得が終わらないまま枠が「読み込み中」に固定されないよう、全体に時間制限を設ける。
// navigator.onLineがtrueのまま通信できない場合、アクセストークンが期限切れだと
// 認証の読み取りの更新の再試行だけで約25秒（SDKの内部で、設定で変えられない）、通信が応答しないと数分止まるため。
// 超えたら原因を断定せずerrorとして再試行できるようにする（遅れて届いた結果は捨てる）。
// 利用者の操作が待つ通信（プリセットの保存・削除）の上限にも使う。サインアウトの上限は認証の機能が持つ。
export const FETCH_TIMEOUT_MS = 10_000;

// 取得の結果に頼らない確認の待ちの上限(サインインの確認、アプリの更新の切り替え)。
export const SHORT_WAIT_MS = 1_000;
